#!/usr/bin/env sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<'SQL'
\getenv app_password PROMO_APP_PASSWORD
CREATE ROLE promo_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'app_password';
GRANT CONNECT ON DATABASE promo TO promo_app;
GRANT USAGE ON SCHEMA public TO promo_app;
ALTER DEFAULT PRIVILEGES FOR ROLE promo IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO promo_app;
ALTER DEFAULT PRIVILEGES FOR ROLE promo IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO promo_app;
SQL
